// Builds lib/states.ts: single-stroke SVG outlines for PA, IL, NV and MD.
// Source: us-atlas v3 (states-10m.json), derived from the U.S. Census Bureau
// cartographic boundary files, which are in the public domain. https://github.com/topojson/us-atlas
import { readFile, writeFile } from "node:fs/promises";
import { feature } from "topojson-client";
import { geoConicConformal, geoPath, geoCentroid } from "d3-geo";

const topo = JSON.parse(await readFile("node_modules/us-atlas/states-10m.json", "utf8"));
const states = feature(topo, topo.objects.states);
const WANT = { "42": "pennsylvania", "17": "illinois", "32": "nevada", "24": "maryland" };
const SIZE = 240;
const out = {};
for (const f of states.features) {
  const slug = WANT[f.id];
  if (!slug) continue;
  const [lon, lat] = geoCentroid(f);
  const proj = geoConicConformal().parallels([lat - 2, lat + 2]).rotate([-lon, 0]).center([0, lat]);
  proj.fitExtent([[6, 6], [SIZE - 6, SIZE - 6]], f);
  const d = geoPath(proj).digits(1)(f);
  const [[x0, y0], [x1, y1]] = geoPath(proj).bounds(f);
  out[slug] = { d, box: [x0, y0, x1 - x0, y1 - y0].map((n) => Math.round(n * 10) / 10) };
}
const ts = `// AUTO-GENERATED by scripts/build-states.mjs. Do not edit by hand.
// State boundaries from us-atlas v3 (states-10m.json, https://github.com/topojson/us-atlas),
// derived from U.S. Census Bureau cartographic boundary files (public domain).
// Each path is fitted to a ${SIZE}x${SIZE} box with a conic conformal projection centred on the state.

export type StateSlug = "pennsylvania" | "illinois" | "nevada" | "maryland";

export const STATE_VIEWBOX = "0 0 ${SIZE} ${SIZE}";

export const STATE_OUTLINES: Record<StateSlug, { d: string; box: [number, number, number, number] }> = ${JSON.stringify(out, null, 2)};
`;
await writeFile("lib/states.ts", ts);
for (const [k, v] of Object.entries(out)) console.log(k, v.d.length, v.box);
